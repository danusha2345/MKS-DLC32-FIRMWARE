#pragma once

/*
    SDLineReader.h — чтение строки G-кода из произвольного источника байтов.

    Вынесено из SDCard.cpp, чтобы логику разбора строки можно было проверять
    нативными тестами (test/test_sd_line_reader) без SD-карты и Arduino-фреймворка.
    Здесь нет ни одной зависимости от железа: источник байтов задаётся колбэком.
*/

#include <stddef.h>
#include <stdint.h>

// Результат чтения строки. Раньше всё это возвращалось одним bool, и вызывающий
// не мог отличить конец файла от ошибки/слишком длинной строки — задание
// завершалось с рапортом об успехе посреди файла.
enum class SDLineResult : uint8_t {
    Line,       // строка прочитана (в т.ч. пустая)
    Eof,        // источник закончился
    TooLong,    // строка не влезает в буфер
    ReadError,  // ошибка чтения
};

// Значения, которые источник возвращает вместо байта.
const int SD_LINE_EOF   = -1;
const int SD_LINE_ERROR = -2;

// Колбэк-источник: >= 0 — очередной байт, SD_LINE_EOF — данные кончились,
// SD_LINE_ERROR — сбой чтения.
typedef int (*sd_byte_source)(void* ctx);

// Читает одну строку до '\n' (сам перевод строки в буфер не попадает).
// Всегда терминирует line, если cap > 0. Максимальная длина строки — cap-1.
SDLineResult sd_read_line(char* line, size_t cap, sd_byte_source next, void* ctx);
